#!/usr/bin/env node
/**
 * Copies the web app's scene art (web/src/components/scenes/art/**.svg) into
 * src/scenes/art.generated.ts as XML strings, for react-native-svg's SvgXml.
 * Run after changing any SVG on the web side:  node scripts/sync-art.mjs
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = fileURLToPath(new URL('.', import.meta.url));
const root = join(here, '../../web/src/components/scenes/art');
const out = join(here, '../src/scenes/art.generated.ts');

const files = [];
(function walk(dir) {
  for (const name of readdirSync(dir).sort()) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p);
    else if (name.endsWith('.svg')) files.push(p);
  }
})(root);

const clean = (xml) =>
  xml
    .replace(/<\?xml[^>]*\?>/g, '')
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/\s+/g, ' ')
    .replace(/> </g, '><')
    .trim();

let body = '';
for (const f of files) {
  const key = relative(root, f).replace(/\.svg$/, '');
  body += `  ${JSON.stringify(key)}: ${JSON.stringify(clean(readFileSync(f, 'utf8')))},\n`;
}

writeFileSync(
  out,
  `/* eslint-disable */\n// Generated by scripts/sync-art.mjs from web/src/components/scenes/art. Do not edit.\n\nexport const ART = {\n${body}} as const;\n\nexport type ArtKey = keyof typeof ART;\n`,
);
console.log(`Wrote ${files.length} SVGs to ${relative(process.cwd(), out)}`);
