#!/usr/bin/env node
/**
 * Copies the web app's theme data (web/src/lib/themes.ts) into src/themes/themes.ts, swapping
 * the CSS font stacks for the app's font keys. Run after changing themes on the web side:
 *   node scripts/sync-themes.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const here = fileURLToPath(new URL('.', import.meta.url));
const src = readFileSync(`${here}../../web/src/lib/themes.ts`, 'utf8');
const out = `${here}../src/themes/themes.ts`;

let s = src.replace(
  /^const SANS = [\s\S]*?^const PIXEL = [^\n]*\n/m,
  `/** Font families, resolved to a bundled font file per weight by fontFor() (see fonts.ts). */
const SANS: FontKey = "sans";
const SERIF: FontKey = "serif";
/** Geist Mono: Magic 8 Ball's terse oracle readout. */
const MONO: FontKey = "mono";
/** Geist Serif's Triangle cut: every dot (i, j, colon, full stop) is a little triangle. */
const SERIF_TRIANGLE: FontKey = "serifTriangle";
/** Geist Pixel's Square cut: every letter built from square pixels, like an arcade screen. */
const PIXEL: FontKey = "pixel";
`,
);
if (s === src) throw new Error('Font constants not found; update sync-themes.mjs');
s = s
  .replace('import { scallop } from "@/lib/scallop";', 'import { scallop } from "@/lib/scallop";\nimport type { FontKey } from "./fonts";')
  // Hidden themes stay reachable for the scene preview
  .replace('const ALL_THEMES: Theme[] = [', 'export const ALL_THEMES: Theme[] = [')
  .replace(/titleFont: string;/, 'titleFont: FontKey;')
  .replace(/timeFont: string;/, 'timeFont: FontKey;')
  // Any other inline font stack: the first Geist variable names the family
  .replace(/"var\(--font-geist-([a-z-]+)\)[^"]*"/g, (_, name) => {
    const key = { sans: 'sans', serif: 'serif', mono: 'mono', 'serif-triangle': 'serifTriangle', 'serif-heart': 'serifHeart', 'pixel-square': 'pixel' }[name];
    if (!key) throw new Error(`Unknown font ${name}; add it to fonts.ts and sync-themes.mjs`);
    return `"${key}"`;
  });
s =
  '// Generated by scripts/sync-themes.mjs from web/src/lib/themes.ts. Edit the web file, then re-run.\n' +
  '// CSS strings (disc gradients, shadows) go straight to React Native backgroundImage / boxShadow.\n\n' +
  s;
writeFileSync(out, s);
console.log('Wrote', out);
