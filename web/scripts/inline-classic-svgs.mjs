// Turns web/src/components/scenes/art/classic/village/*.svg into sunrise-village-art.ts.
// Usage (from web/): node scripts/inline-classic-svgs.mjs
//
// The art follows docs/classic-theme-svg-prompts.md. The village recolours it with the sunrise,
// so palette fills become CSS variables (with the original colour as the fallback); cottage
// windows come out as data so the code can light them one by one.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const artDir = "src/components/scenes/art/classic/village";
const outFile = "src/components/scenes/sunrise-village-art.ts";

/** Palette colours the village recolours, and the CSS variable each one becomes. */
const VARS = {
  "#FFF6EC": "--lc-wall",
  "#E98A7B": "--lc-roof",
  "#B985A6": "--lc-roof2",
  "#A794AF": "--lc-glass",
  "#704C68": "--lc-wood",
  "#80AD78": "--lc-canopy",
  "#9CBE92": "--lc-light",
  "#9B705E": "--lc-trunk",
};

const read = (name) => readFileSync(join(artDir, `${name}.svg`), "utf8");
const attr = (tag, name) => tag.match(new RegExp(`\\s${name}="([^"]*)"`))?.[1];
const num = (v) => Number(Number(v).toFixed(2));
const inner = (src) => src.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "");
const viewBox = (src) => attr(src.match(/<svg[^>]*>/)[0], "viewBox").split(/\s+/).map(Number);

/** Markup ready to inline: no ids or titles, palette fills as CSS variables. */
function clean(markup) {
  return markup
    .replace(/<title[\s\S]*?<\/title>/g, "")
    .replace(/\sid="[^"]*"/g, "")
    .replace(/\sfill="(#[0-9A-Fa-f]{6})"/g, (m, hex) => {
      const v = VARS[hex.toUpperCase()];
      return v ? ` style="fill:var(${v},${hex})"` : m;
    })
    .replace(/\s+/g, " ")
    .replace(/> </g, "><")
    .trim();
}

const element = (src, id) => src.match(new RegExp(`<(path|rect|circle)[^>]*id="${id}"[^>]*/>`))?.[0];
const group = (src, id) => src.match(new RegExp(`<g[^>]*id="${id}"[^>]*>([\\s\\S]*?)</g>`))?.[0];
const subpaths = (d) => d.trim().split(/(?=M)/).map((s) => s.trim());
const withD = (tag, d) => tag.replace(/\sd="[^"]*"/, ` d="${d}"`).replace(/\sfill-rule="[^"]*"/, "");

/**
 * A cottage, layered so a dormer reads right: the main wall, chimney and roof underneath; then
 * any further wall pieces (a dormer's face) and roof pieces (its little roof), and the door.
 */
function cottage(name) {
  const src = read(name);
  const [, , w, h] = viewBox(src);
  const wall = element(src, "wall");
  const roof = element(src, "roof");
  const chimney = element(src, "chimney");
  const door = element(src, "door");
  const wallSubs = subpaths(attr(wall, "d"));
  const roofSubs = subpaths(attr(roof, "d"));
  const under = [withD(wall, wallSubs[0]), chimney ?? "", withD(roof, roofSubs[0])].join("");
  const over = [
    ...wallSubs.slice(1).map((d) => withD(wall, d)),
    ...roofSubs.slice(1).filter((d) => !wallSubs.includes(d)).map((d) => withD(roof, d)),
    door ?? "",
  ].join("");
  const windows = [...(group(src, "windows") ?? "").matchAll(/<rect[^>]*>/g)].map(([r]) =>
    ["x", "y", "width", "height"].map((k) => num(attr(r, k))),
  );
  const smoke = chimney
    ? [num(Number(attr(chimney, "x")) + Number(attr(chimney, "width")) / 2), num(attr(chimney, "y"))]
    : null;
  return { name, w, h, under: clean(under), over: clean(over), windows, smoke };
}

function windmill() {
  const tower = read("windmill-tower");
  const [, , tw, th] = viewBox(tower);
  const win = element(tower, "window") ?? group(tower, "window").match(/<circle[^>]*>/)[0];
  const hub = element(tower, "hub");
  const body = inner(tower).replace(group(tower, "window") ?? win, "");
  return {
    w: tw,
    h: th,
    markup: clean(body),
    window: ["cx", "cy", "r"].map((k) => num(attr(win, k))),
    hub: [num(attr(hub, "cx")), num(attr(hub, "cy"))],
    sails: clean(inner(read("windmill-sails"))),
    /** The sails' own grid: they turn about its centre. */
    sailsSize: viewBox(read("windmill-sails"))[2],
  };
}

const COTTAGES = ["cottage-01", "cottage-02", "cottage-03", "cottage-04"].map(cottage);
const ROOSTER = Object.fromEntries(
  ["asleep", "standing", "crowing"].map((pose) => [pose, clean(inner(read(`rooster-${pose}`)))]),
);
const TREE = Object.fromEntries(["round", "poplar", "apple"].map((k) => [k, clean(inner(read(`tree-${k}`)))]));
const MILL = windmill();

const out = `// Generated by scripts/inline-classic-svgs.mjs from ./art/classic/village. Don't edit by hand:
// edit the SVGs (see docs/classic-theme-svg-prompts.md) and re-run the script.
// Palette fills are CSS variables (--lc-wall, --lc-roof, ...) so the village can recolour them.

export type CottageArt = {
  name: string;
  /** The art's grid: ground at y = h, the bottom 20 hidden behind the hill. */
  w: number;
  h: number;
  /** Main wall, chimney and roof. */
  under: string;
  /** Drawn over the roof: a dormer's face and roof, and the door. */
  over: string;
  /** x, y, w, h: lit one by one. */
  windows: number[][];
  /** Top centre of the chimney, where the smoke comes out. */
  smoke: number[] | null;
};

export const COTTAGE_ART: CottageArt[] = ${JSON.stringify(COTTAGES, null, 2)};

/** The rooster facing right on a 64 grid, feet at the bottom: one per pose. */
export const ROOSTER_ART = ${JSON.stringify(ROOSTER, null, 2)} as const;

/** Trees on an 80 × 110 grid, trunk standing at (40, 110). */
export const TREE_ART = ${JSON.stringify(TREE, null, 2)} as const;

/** The windmill tower (ground at y = h), its window (cx, cy, r) and hub; the sails turn about the centre of their own square grid. */
export const MILL_ART = ${JSON.stringify(MILL, null, 2)};
`;

writeFileSync(outFile, out);
console.log(`Wrote ${outFile}: ${COTTAGES.length} cottages, 3 rooster poses, 3 trees, windmill.`);
